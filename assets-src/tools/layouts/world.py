"""The world composer (docs/WORLD_PLAN.md 2.4-2.9, QUEST 3.5) -> assets-src/maps/overworld.yaml, the 192x192 world.

  python3 -I assets-src/tools/layouts/world.py                       # compose, check, write the world source
  python3 -I assets-src/tools/layouts/world.py --check-bands         # checks 1, 2 and 4 only: prints `bands: OK`
  python3 -I assets-src/tools/layouts/world.py --owned-chunks <r>    # the files region <r> may change (G3)

Each region module `world_<r>.py` returns a RegionOut in world cells (A1: the act-1 block of overworld.py at
A1_ORIGIN, `world_a1.py`; the others are ocean stubs until their O tranche builds them). The composer pastes them,
leaves the edge bands ocean, fills the seams and the placeholder walls of the stub regions, runs the global checks
(world_checks.py), each region's own map checks (map_checks_region.py) and writes the source. It is the only writer
of `overworld.yaml`; `overworld.py` is a shim that runs it.
"""
from __future__ import annotations

import contextlib
import io
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(1, str(HERE.parent))
import world_a1, world_earth, world_elf, world_fire, world_ordeal, world_water, world_wind  # noqa: E401, E402
import world_checks as WC  # noqa: E402
from common import write_map  # noqa: E402
from world_api import (BASIN_SEEDS, BOXES, PLACEHOLDER_WALLS, SEAMS, UNSET, WATER, WORLD_H, WORLD_W,  # noqa: E402
                       RegionOut)
from world_geom import band_cells, bbox, chunk_files, flood, is_walkable, owned_chunks, owner_grid  # noqa: E402

REGIONS = ["a1", "elf", "earth", "fire", "ordeal", "water", "wind"]      # pre-seeded; no tranche edits the list
MODULES = {"a1": world_a1, "elf": world_elf, "earth": world_earth, "fire": world_fire, "ordeal": world_ordeal,
           "water": world_water, "wind": world_wind}
LIST_KEYS = ("objects", "inspect", "npcs", "keyItemGates", "encounterZones", "vehicles", "transitions", "patches",
             "docks", "hazards", "ambient")
HEADER = """GENERATED by assets-src/tools/layouts/world.py - edit the region scripts (layouts/world_<region>.py), not this file.
The 192x192 world (docs/WORLD_PLAN.md 2): act 1 (layouts/overworld.py) at A1_ORIGIN (64, 64), the other regions,
the composer's edge bands, seams and placeholder walls. Compiled by assets-src/tools/build_map.py.
ground legend: . grass  f forest  m mountain  s sand  , dirt road  r river  o ocean  = bridge  ≈ lake"""


def compose(outs: dict[str, RegionOut]) -> list[list[str]]:
    world = [[WATER] * WORLD_W for _ in range(WORLD_H)]       # bands default to ocean, the outer edge always
    for r, out in outs.items():
        b = bbox(BOXES[r])
        for j, row in enumerate(out.ground[:b.h]):
            for i, ch in enumerate(row[:b.w]):
                if ch != UNSET:
                    world[b.y0 + j][b.x0 + i] = ch
    for p in PLACEHOLDER_WALLS:                                # 5.1: only Water cells, so o -> m (or grass) only
        if outs[p.region].stub:
            for x, y in p.rect.cells():
                if world[y][x] == WATER:
                    world[y][x] = p.fill
    for s in SEAMS.values():
        for x, y in s.rect.cells():
            world[y][x] = s.fill
    return world


def regions() -> tuple[dict[str, RegionOut], dict, set, list]:
    own = owner_grid()
    band = band_cells(own)
    outs, keys = {}, {}
    for r in REGIONS:
        if r == "a1":
            outs[r], keys = world_a1.build(band)
        else:
            outs[r] = MODULES[r].build(band)
    return outs, keys, band, own


def source(outs: dict[str, RegionOut], keys: dict, world: list[list[str]], cuts: dict) -> dict:
    """The world source document (map keys from A1, the regions' lists in REGIONS order)."""
    doc = {k: keys[k] for k in ("id", "name", "camp", "kits", "music", "terrain")}
    roots = [e for out in outs.values() for e in (out.checks.get("reach_roots") or list(out.entrances))]
    later = [e for out in outs.values() for e in out.checks.get("unreachable_ok") or []]
    # the composer's own walkable cells (a grass seam, the grass placeholder rows beside it) that no region's land
    # reaches yet: listed cell by cell, so a built region that leaves land cut off still fails
    ents = {k: tuple(v) for out in outs.values() for k, v in out.entrances.items()}
    seen = flood(world, [ents[e] for e in roots + later if e in ents], is_walkable)
    mine = [c for s in SEAMS.values() for c in s.rect.cells()]
    mine += [c for p in PLACEHOLDER_WALLS if outs[p.region].stub for c in p.rect.cells()]
    later += [list(c) for c in dict.fromkeys(mine) if is_walkable(world[c[1]][c[0]]) and c not in seen]
    doc.update({"sealed_edges": True, "art_coverage": True, "no_unreachable_walkable": {"reach_roots": roots},
                "unreachable_ok": later, "entrances": {k: v for out in outs.values() for k, v in out.entrances.items()}})
    for k in LIST_KEYS:
        doc[k] = [dict(i) for out in outs.values() for i in getattr(out, k)]
        if k == "inspect":
            doc["encounterRate"], doc["encounters"] = keys["encounterRate"], keys["encounters"]
    zones = {z: v for out in outs.values() for z, v in (out.battleBackgrounds.get("zones") or {}).items()}
    doc["battleBackgrounds"] = {**keys["battleBackgrounds"], "zones": zones}
    doc = {k: v for k, v in doc.items() if v != [] or k in ("npcs", "transitions")}
    doc["regions"] = {r: {"stub": out.stub, "checks": {k: v for k, v in out.checks.items()
                                                        if k not in ("legacy_ids", "anchors_pending")}}
                      for r, out in outs.items()}
    # NW-1 (docs/NATURAL_WORLD_PLAN.md 5.2, 4.3): the named places quest.yaml, the scenarios and the cutscenes use,
    # and the basin seeds the verifier reads from the map instead of a copy of BASIN_SEEDS
    doc["spots"] = {k: {"at": list(v["at"]), "kind": v["kind"]} for out in outs.values() for k, v in out.spots.items()}
    doc["world"] = {**keys["world"], "basins": {k: list(v) for k, v in BASIN_SEEDS.items()}, "cuts": cuts}
    return doc


def main(argv: list[str]) -> int:
    if argv[:1] == ["--owned-chunks"]:
        if len(argv) != 2 or argv[1] not in BOXES:
            raise SystemExit(f"usage: world.py --owned-chunks <{'|'.join(BOXES)}>")
        with contextlib.redirect_stdout(io.StringIO()):           # only the paths on stdout
            outs, *_ = regions()
        for p in chunk_files("overworld", owned_chunks(argv[1])):
            print(p)
        for p in outs[argv[1]].patches:
            print(f"assets/maps/ai/overworld/patch_{p['id']}.png")
        return 0
    if argv not in ([], ["--check-bands"]):
        raise SystemExit("usage: world.py [--check-bands | --owned-chunks <region>]")
    outs, keys, band, own = regions()
    world = compose(outs)
    errs = WC.check_bands(outs, own, band, world)
    if errs:
        print("bands: FAIL\n  " + "\n  ".join(errs))
        return 1
    print("bands: OK")
    if argv:
        return 0
    patches = [p for out in outs.values() for p in out.patches]
    aldi, ocean, errs = WC.basins(world, patches)
    errs += WC.docks(world, patches, [(r, d) for r, out in outs.items() for d in out.docks])
    if errs:
        print("\n".join(errs))
        return 1
    print(f"basins: OK (aldi {len(aldi)} cells, ocean {len(ocean)} cells; canal joins)")
    walls, errs = WC.wall_cells(world, outs)
    cuts, more = WC.cuts(world, aldi, ocean, outs, walls)
    errs += more + WC.ids(outs) + WC.anchors(outs, {k: v for o in outs.values() for k, v in o.entrances.items()})
    errs += WC.reachable(world, patches, outs)
    doc = source(outs, keys, world, cuts)
    import map_checks_region as MR  # noqa: PLC0415  (numpy and the compiler legend; not needed for the bands)
    for r in REGIONS:
        errs += [f"{r}: {e}" for e in MR.check(doc, world, r)]
    if errs:
        print("world: FAIL\n  " + "\n  ".join(errs))
        return 1
    print("cuts: " + ", ".join(f"{k} {len(v)}" for k, v in cuts.items()))
    print(write_map("overworld", HEADER, doc, "\n".join("".join(r) for r in world) + "\n"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
