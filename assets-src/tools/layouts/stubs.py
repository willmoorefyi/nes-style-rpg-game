"""Stub sources for the pass W canon (docs/WORLD_PLAN.md D-W8, 5.1, G16) -> assets-src/maps/<id>.yaml.

  python3 -I assets-src/tools/layouts/stubs.py                    # write a stub for every canon id still without a map
  python3 -I assets-src/tools/layouts/stubs.py --count <tranche|all>   # report only; always exits 0
  python3 -I assets-src/tools/layouts/stubs.py --check <tranche|all>   # the same, exits 1 while any stub is left

A stub is a 12x10 room (header `STUB generated by stubs.py`) with each canon entrance of the id, a transition beside
each entrance that has a link, and a walking exit gap on the bottom row when the canon says the map has one. Floors
also get `exit` (MapData.exit, the EXIT spell). A source without the stub header is a real map and is never touched;
a stub source is rewritten, so the output always follows the canon. The tranche that owns an id replaces its stub
with the real layout (5.3); `--check <tranche>` is its gate G16.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import MAPS, write_map  # noqa: E402
from world_canon import CANON, TRANCHES, MapRow, owned  # noqa: E402

MARK = "STUB generated by stubs.py"
W, H = 12, 10
GAP = (5, H - 1)                             # the exit gap; the first entrance stands on the cell above it
# (entrance cell, transition cell) slots for the other entrances: a row under the north wall, and a row above the
# bottom corridor that leaves columns 4-6 free, so every slot is reached without crossing a transition
SLOTS = [((x, 4), (x, 3)) for x in range(1, W - 1)] + [((x, 6), (x, 7)) for x in (1, 2, 3, 7, 8, 9, 10)]
MUSIC = {"town": "town", "house": "town", "castle": "town", "shop": "shop", "inn": "shop", "site": "dungeon",
         "floor": "dungeon"}
LEGEND = "legend: W wall top  F wall face  - stone floor"


def is_stub(path: Path) -> bool:
    if not path.exists():
        return False
    with path.open(encoding="utf-8") as f:
        return MARK in f.readline()


def left(ids: list[str]) -> list[str]:
    """Canon ids whose source is missing or still a stub."""
    return [i for i in ids if not (MAPS / f"{i}.yaml").exists() or is_stub(MAPS / f"{i}.yaml")]


def stub_doc(r: MapRow) -> tuple[dict, str]:
    names = [n for n, _ in r.entrances]
    if len(names) - 1 > len(SLOTS):
        raise SystemExit(f"stubs: {r.id} has {len(names)} entrances, a stub room holds {len(SLOTS) + 1}")
    cells = {names[0]: (GAP[0], GAP[1] - 1)}
    beside: dict[str, tuple[int, int]] = {}
    for name, (ent, trans) in zip(names[1:], SLOTS):
        cells[name], beside[name] = ent, trans
    transitions = []
    if r.exit_walk:
        transitions.append({"x": GAP[0], "y": GAP[1], "targetMap": r.exit[0], "targetEntrance": r.exit[1]})
    for here, mid, ent in r.links:
        if here == names[0] and r.exit_walk and (mid, ent) == r.exit:
            continue                             # the exit gap already leads there
        x, y = beside.get(here, (GAP[0], GAP[1]))
        if here == names[0]:                     # a link by the first entrance (a floor's stair back) uses the gap
            x, y = GAP
        transitions.append({"x": x, "y": y, "targetMap": mid, "targetEntrance": ent})
    rows = ["W" * W, "W" + "F" * (W - 2) + "W", "W" + "F" * (W - 2) + "W"] + ["W" + "-" * (W - 2) + "W"] * 6
    gap_open = any((t["x"], t["y"]) == GAP for t in transitions)
    rows.append("W" * GAP[0] + ("-" if gap_open else "W") + "W" * (W - GAP[0] - 1))
    doc = {"id": r.id, "name": r.name, "kits": ["interior"], "music": MUSIC[r.kind],
           "entrances": {n: list(cells[n]) for n in names}, "objects": [], "npcs": [], "transitions": transitions,
           "encounterRate": {"min": 999, "max": 999}, "encounters": [], "canSave": True}
    if r.kind == "floor":
        doc["exit"] = {"map": r.exit[0], "entrance": r.exit[1]}
    return doc, "\n".join(rows) + "\n"


def write_all() -> None:
    wrote = kept = 0
    for mid, r in CANON.items():
        path = MAPS / f"{mid}.yaml"
        if path.exists() and not is_stub(path):
            kept += 1
            continue
        doc, ground = stub_doc(r)
        header = (f"{MARK} - a placeholder for {r.owner}, who replaces it with the real map (docs/WORLD_PLAN.md "
                  f"D-W8).\nKind {r.kind}; the entrances, links and exit come from layouts/world_canon.py.\n{LEGEND}")
        write_map(mid, header, doc, ground)
        wrote += 1
    print(f"stubs: wrote {wrote} stub sources, kept {kept} real maps ({len(CANON)} canon ids)")


def tranche_arg(arg: str) -> str:
    if arg == "all":
        return arg
    t = next((t for t in TRANCHES if t.lower() == arg.lower()), None)
    if t is None:
        raise SystemExit(f"stubs: unknown tranche {arg!r}; one of all, {', '.join(TRANCHES)}")
    return t


def main(argv: list[str]) -> int:
    if not argv:
        write_all()
        return 0
    if len(argv) != 2 or argv[0] not in ("--count", "--check"):
        raise SystemExit("usage: stubs.py [--count|--check <tranche|all>]")
    t = tranche_arg(argv[1])
    n = len(left(owned(t)))
    print(f"stubs: {n} left" + ("" if t == "all" else f" for {t}"))
    return 1 if argv[0] == "--check" and n else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
