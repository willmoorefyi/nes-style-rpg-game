/**
 * WAT-D's Sea Shrine and stage S24 (docs/WORLD_PLAN.md 3.2, 4.0.2, 4.6, 6.4, D-W14), on the compiled maps and the real
 * quest data: the submarine's pier in B3 (the nave) leads back to Onrac's dry dock once WAT-T's Onrac is built; the
 * nave splits up (B2, then B1, the mermaids' grotto, a dead end with hint NPCs and no monsters) and down (B4, two
 * routes that meet only in the stair room, each to its own stairwell, then B5); B5's boss lies north of the arrival;
 * the chest counts 2 / 3 / 3 / 4 / 2; no chest cuts off a way on from any arrival; the slab comes only from
 * `wat_drowned_falls`; then the S24 walk.
 *
 * Onrac (and its submarine gate, `requiredItem: oxyale`) is WAT-T's. Until it is compiled, proofs (b) and (c) of
 * `--stage S24` can't hold (the shrine is entered without the gate, and the EXIT spell's way back in runs through
 * Onrac), so those cases run only once `onrac` is loaded.
 */
import { describe, expect, it } from 'vitest';
import { existsSync, readFileSync } from 'node:fs';
import { parse } from 'yaml';
import type { MapData } from '../../../src/types/index.js';
import { npcOutcome, type FieldState } from '../../../src/systems/fieldRules.js';
import { loadQuestWorld } from '../../../src/progression/questData.js';
import { closure, createQuestContext } from '../../../src/progression/questProofs.js';
import { runCoreProofs } from '../../../src/progression/questReport.js';
import { bossPosition, deadEnds, stairGraph } from '../originalityChecks.js';
import { distances, key } from '../elf/marshPaths.js';

const load = (id: string): MapData => parse(readFileSync(`assets/maps/ai/${id}.yaml`, 'utf-8')) as MapData;
const [b1, b2, b3, b4, b5] = [1, 2, 3, 4, 5].map((n) => load(`sea-shrine-b${n}`));
const ALL = [b1, b2, b3, b4, b5];
const cutscenes = parse(readFileSync('assets/data/cutscenes.yaml', 'utf-8')) as Array<{ id: string; steps: Array<Record<string, unknown>> }>;
const links = (m: MapData, to: string): string[] => [...new Set(m.transitions.filter((t) => t.targetMap === to).map((t) => t.targetEntrance!))].sort();
const at = (m: MapData, e: string): [number, number] => m.entrances![e] as [number, number];
const cell = (m: MapData, to: string, ent: string): string => {
  const t = m.transitions.find((x) => x.targetMap === to && x.targetEntrance === ent)!;
  return `${t.x},${t.y}`;
};
/** WAT-T's Onrac is built (its source is no stub): then the nave's pier links back to its dry dock. */
const ONRAC_BUILT = existsSync('assets-src/maps/onrac.yaml')
  && !readFileSync('assets-src/maps/onrac.yaml', 'utf-8').split('\n', 1)[0].includes('STUB generated by stubs.py');
const state = (flags: string[]): FieldState => ({ flags: new Set(flags), items: new Set(), vehicles: [], mode: 'walking' } as FieldState);

describe('WAT-D: the Sea Shrine floors', () => {
  it('B3, the nave: the stair up to B2, the stairwell down to B4, and (once Onrac is built) the pier to onrac:dry_dock', () => {
    expect(links(b3, 'onrac')).toEqual(ONRAC_BUILT ? ['dry_dock'] : []);
    expect(links(b3, 'sea-shrine-b2')).toEqual(['down']);
    expect(links(b3, 'sea-shrine-b4')).toEqual(['arrival']);
    const d = distances(b3, at(b3, 'nave'));
    const ways = [['sea-shrine-b2', 'down'], ['sea-shrine-b4', 'arrival'], ...(ONRAC_BUILT ? [['onrac', 'dry_dock']] : [])];
    for (const [to, e] of ways) expect(d.has(cell(b3, to, e)), `${to}:${e}`).toBe(true);
    expect(Object.keys(b3.entrances!).sort()).toEqual(['down', 'nave', 'up']);
  });

  it('up: B2 links B3 and B1; B1, the grotto, is a dead end with no monsters and at least 2 hint NPCs', () => {
    expect(links(b2, 'sea-shrine-b3')).toEqual(['up']);
    expect(links(b2, 'sea-shrine-b1')).toEqual(['down']);
    expect([...new Set(b1.transitions.map((t) => t.targetMap))]).toEqual(['sea-shrine-b2']);
    expect(links(b1, 'sea-shrine-b2')).toEqual(['up']);
    expect(b1.encounters ?? []).toEqual([]);
    expect(b1.npcs.filter((n) => n.id.endsWith('_hint')).length).toBeGreaterThanOrEqual(2);
    expect(b1.npcs.filter((n) => !n.chestItem).length).toBeGreaterThanOrEqual(4);
    // the cloister's walk is a ring: both ways round reach the stair up
    expect(distances(b2, at(b2, 'down')).has(cell(b2, 'sea-shrine-b1', 'down'))).toBe(true);
  });

  it('down: B4 has two routes from the stair room, each to its own stairwell; they meet only in the stair room', () => {
    expect(links(b4, 'sea-shrine-b3')).toEqual(['down']);
    expect(links(b4, 'sea-shrine-b5')).toEqual(['arrival', 'arrival_west']);
    expect(links(b5, 'sea-shrine-b4')).toEqual(['down', 'down_west']);
    const d = distances(b4, at(b4, 'arrival'));
    expect(d.has(cell(b4, 'sea-shrine-b5', 'arrival')) && d.has(cell(b4, 'sea-shrine-b5', 'arrival_west'))).toBe(true);
    const room = new Set<string>();
    for (let y = 4; y <= 9; y++) for (let x = 36; x <= 43; x++) room.add(key(x, y));
    expect(distances(b4, at(b4, 'down'), room).has(cell(b4, 'sea-shrine-b5', 'arrival_west'))).toBe(false);
    expect(stairGraph(ALL).branching).toBe(true);
  });

  it('B5: the boss lies north of the arrival at a path of at least 30, and both arrivals reach it', () => {
    const b = bossPosition(b5)!;
    expect(b.octant).toBe('N');
    expect(b.path).toBeGreaterThanOrEqual(30);
    const boss = b5.scriptedEncounters!.find((e) => e.isBoss)!;
    expect(distances(b5, at(b5, 'arrival_west')).has(key(boss.x, boss.y))).toBe(true);
    expect(b5.entrances?.boss).toBeDefined();
  });

  it('chests: B1 2, B2 3, B3 3, B4 4, B5 2, all CHEST_WAT_D_*; none cuts off a way on from any arrival', () => {
    const chests = (m: MapData) => m.npcs.filter((n) => n.chestItem);
    expect(ALL.map((m) => chests(m).length)).toEqual([2, 3, 3, 4, 2]);
    for (const m of ALL) for (const c of chests(m)) expect(c.chestFlag).toMatch(/^CHEST_WAT_D_/);
    for (const m of ALL) {
      for (const e of Object.keys(m.entrances ?? {})) {
        const open = distances({ ...m, npcs: [] }, at(m, e));
        const withNpcs = distances(m, at(m, e));
        for (const t of m.transitions) {
          const k = `${t.x},${t.y}`;
          if (open.has(k)) expect(withNpcs.has(k), `${m.id} ${e} -> ${t.targetMap}`).toBe(true);
        }
      }
    }
  });

  it('every floor: EXIT to Onrac\'s coast, the S24 roster, the staged backgrounds, 2+ dead ends; B4 and B5 canSave false', () => {
    const roster = new Set(['sahagin_prince', 'deepeyes', 'sea_snake', 'sea_scorpion', 'sea_troll', 'ghost', 'water_elemental', 'water_naga']);
    for (const m of ALL) {
      expect(m.exit).toEqual({ map: 'overworld', entrance: 'wat_onrac' });
      expect((m.encounters ?? []).flatMap((e) => (e.groups ?? []).map((g) => g.id)).every((i) => roster.has(i))).toBe(true);
      expect(m.battleBackgrounds?.default).toBe(m === b5 ? 'throne_kraken' : 'water_temple');
      expect(deadEnds(m)).toBeGreaterThanOrEqual(2);
    }
    for (const m of [b2, b3, b4, b5]) expect((m.encounters ?? []).length).toBeGreaterThan(0);
    expect([b4.canSave, b5.canSave]).toEqual([false, false]);
  });
});

describe('WAT-D: the Drowned Sovereign and the slab', () => {
  it('talking to the king starts drowned_sovereign once; wat_drowned_falls alone gives the slab and lights the crystal', () => {
    const king = b5.npcs.find((n) => n.id === 'wat_d_sovereign')!;
    expect(npcOutcome(king, state([]), b5.scriptedEncounters ?? []).battle).toBe('WATER_CRYSTAL_LIT');
    expect(npcOutcome(king, state(['WATER_CRYSTAL_LIT']), b5.scriptedEncounters ?? []).present).toBe(false);
    const enc = b5.scriptedEncounters!.find((e) => e.npc === 'wat_d_sovereign')!;
    expect(enc.enemyIds).toEqual(['drowned_sovereign']);
    expect([enc.isBoss, enc.postVictoryCutscene]).toEqual([true, 'wat_drowned_falls']);
    const gives = cutscenes.filter((c) => c.steps.some((s) => s.type === 'give_item' && s.item === 'slab'));
    expect(gives.map((c) => c.id)).toEqual(['wat_drowned_falls']);
    const falls = cutscenes.find((c) => c.id === 'wat_drowned_falls')!;
    expect(falls.steps.some((s) => s.type === 'set_flag' && s.flag === 'WATER_CRYSTAL_LIT')).toBe(true);
    for (const m of ALL) expect(m.npcs.some((n) => n.chestItem === 'slab' || n.giftItem === 'slab')).toBe(false);
  });
});

describe('WAT-D: stage S24 in assume mode', () => {
  const world = loadQuestWorld({ root: process.cwd() });
  const onrac = world.maps.has('onrac');

  it('the walk replays from the nave and proof (a) holds', () => {
    const s = world.stages.get('S24')!;
    expect(s.status).toBe('built');
    expect(s.walk[s.walk.length - 1]).toBe('sea-shrine-b5:battle:WATER_CRYSTAL_LIT');
    const ctx = createQuestContext(world, { stage: 'S24' });
    for (const r of runCoreProofs(ctx, new Set(['a']))) expect(r.failures.map((f) => f.message), r.proof).toEqual([]);
    const v = closure(ctx).view(ctx.start.place);
    expect([v.flags.has('WATER_CRYSTAL_LIT'), v.items.has('slab')]).toEqual([true, true]);
  });

  it.runIf(onrac)('with Onrac built (WAT-T): proofs (b) and (c) hold', () => {
    const ctx = createQuestContext(world, { stage: 'S24' });
    for (const r of runCoreProofs(ctx, new Set(['b', 'c']))) expect(r.failures.map((f) => f.message), r.proof).toEqual([]);
  });
});
