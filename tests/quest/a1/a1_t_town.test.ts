const load = (id: string): MapData => validateMapData(parse(readFileSync(`assets/maps/ai/${id}.yaml`, 'utf-8'))) as MapData;
const town = load('pravoka');
const ow = load('overworld');
const rooms = canonRows().filter((r) => r.owner === 'A1-T' && r.id !== 'pravoka').map((r) => r.id);
const state = (flags: string[]): FieldState => ({ flags: new Set(flags), items: new Set(), mode: 'walking', vehicles: [] });
type Step = { type: string; flag?: string };
const cutscene = (id: string) => (parse(readFileSync('assets/data/cutscenes.yaml', 'utf-8')) as Array<{ id: string; steps: Step[] }>)
  .find((c) => c.id === id);
const site = JSON.parse(execFileSync('python3', ['-I', '-c', 'import json, sys; sys.path.insert(0, "assets-src/tools/layouts/a1"); '
  + 'import town_pravoka_site as S; print(json.dumps({"gate": S.GATE, "door": S.DOOR, "dock": S.DOCK, "spawn": S.SPAWN, '
  + '"anchor": S.ANCHOR}))'], { encoding: 'utf-8' })) as {
  gate: [number, number]; door: [number, number]; dock: { id: string; x: number; y: number; basin: string };
  spawn: { type: string; x: number; y: number; requiredFlag: string }; anchor: string;
};

/** Walkable cells of a map that cannot reach any of `goals` (4-way, on the terrain alone). */
function cutOff(m: MapData, goals: Array<{ x: number; y: number }>): string[] {
  const ok = (x: number, y: number): boolean => x >= 0 && y >= 0 && x < m.width && y < m.height
    && terrainAllows('walking', baseTerrain(m, x, y));
  const seen = new Set(goals.map((g) => `${g.x},${g.y}`));
  const queue = [...goals];
  while (queue.length) {
    const { x, y } = queue.shift()!;
    for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
      const n = { x: x + dx, y: y + dy };
      if (ok(n.x, n.y) && !seen.has(`${n.x},${n.y}`)) { seen.add(`${n.x},${n.y}`); queue.push(n); }
    }
  }
  const out: string[] = [];
  for (let y = 0; y < m.height; y++) for (let x = 0; x < m.width; x++) if (ok(x, y) && !seen.has(`${x},${y}`)) out.push(`(${x}, ${y})`);
  return out;
}

describe('Pravoka: doors, gate and links (WORLD_PLAN 4.1, canon)', () => {
  it('has the HUD name and its 13 canon maps are built', () => {
    expect(town.name).toBe('Pravoka');
    expect(rooms).toHaveLength(12);
    for (const id of rooms) expect(readFileSync(`assets-src/maps/${id}.yaml`, 'utf-8').split('\n', 1)[0]).toMatch(/^# GENERATED by/);
  });

  it('every canon link: the entrance in front of the door, the door into the room, the room back out to it', () => {
    const row = canonRows().find((r) => r.id === 'pravoka')!;
    for (const [here, map, entrance] of row.links) {
      const [ex, ey] = town.entrances![here];
      const door = town.transitions.find((t) => t.targetMap === map)!;
      expect(door, `${map}`).toBeDefined();
      expect([door.targetEntrance, door.x, door.y]).toEqual([entrance, ex, ey - 1]);
      const room = load(map);
      const back = room.transitions.filter((t) => t.targetMap === 'pravoka');
      expect(back.length).toBeGreaterThan(0);
      for (const t of back) expect(t.targetEntrance).toBe(here);
    }
  });

  it('the land gate: the west edge leads to overworld:a1_pravoka, and the gate entrance stands inside it', () => {
    const out = town.transitions.filter((t) => t.targetMap === 'overworld');
    expect(out.length).toBeGreaterThan(0);
    for (const t of out) expect([t.x, t.targetEntrance]).toEqual([0, site.anchor]);
    const [gx, gy] = town.entrances!.gate;
    expect(out.some((t) => t.y === gy && t.x === gx - 3)).toBe(true);
  });

  it('EXIT-safe: every walkable cell of the town and of each room reaches its way out (the keepers\' side excepted)', () => {
    expect(cutOff(town, town.transitions.filter((t) => t.targetMap === 'overworld'))).toEqual([]);
    for (const id of rooms) {
      const room = load(id);
      const staff = ((parse(readFileSync(`assets-src/maps/${id}.yaml`, 'utf-8')) as { unreachable_ok?: number[][] })
        .unreachable_ok ?? []).map(([x, y]) => `(${x}, ${y})`);
      const keeper = room.npcs.find((n) => n.shopId);
      if (keeper) expect(staff, id).toContain(`(${keeper.x}, ${keeper.y})`);
      expect(cutOff(room, room.transitions.filter((t) => t.targetMap === 'pravoka')).filter((c) => !staff.includes(c)), id)
        .toEqual([]);
    }
  });
});

describe('Pravoka: Bikke and the pirates (S2)', () => {
  const npc = (id: string): MapNPC => town.npcs.find((n) => n.id === id)!;
  const enc = town.scriptedEncounters ?? [];

  it('talking to Bikke starts pirate x9, a boss fight whose victory plays a1_bikke_yields', () => {
    expect(enc).toHaveLength(1);
    const e = enc[0];
    expect(e).toMatchObject({ npc: 'bikke', flag: 'BIKKE_DEFEATED', isBoss: true, postVictoryCutscene: 'a1_bikke_yields' });
    expect(e.enemyIds).toEqual(Array(9).fill('pirate'));
    expect(npcOutcome(npc('bikke'), state(['BRIDGE_BUILT']), enc).battle).toBe('BIKKE_DEFEATED');
    const steps = cutscene('a1_bikke_yields')!.steps;
    expect(steps.filter((s) => s.type === 'set_flag').map((s) => s.flag)).toEqual(['BIKKE_DEFEATED']);
  });

  it('on BIKKE_DEFEATED the captain and his crew are gone, and the dockhands and the beaten captain appear', () => {
    const pirates = town.npcs.filter((n) => n.id.startsWith('pirate_'));
    expect(pirates.length).toBeGreaterThanOrEqual(6);
    for (const p of [...pirates, npc('bikke')]) expect(p.hideIf).toBe('BIKKE_DEFEATED');
    // pass PT (the user's ruling of 2026-11-26): the crew is the untinted pirate_crew sheet, Bikke the sea captain in red
    for (const p of pirates) expect([p.sprite, p.tint], p.id).toEqual(['pirate_crew', undefined]);
    expect(npc('bikke').sprite).toBe('sea_captain');
    expect(npc('bikke').tint).toMatch(/^#[0-9a-f]{6}$/);
    const after = state(['BRIDGE_BUILT', 'BIKKE_DEFEATED']);
    expect(npcOutcome(npc('bikke'), after, enc).present).toBe(false);
    for (const id of ['dockhand_a', 'dockhand_b', 'bikke_after']) {
      expect(npcOutcome(npc(id), state(['BRIDGE_BUILT']), enc).present).toBe(false);
      expect(npcOutcome(npc(id), after, enc).present).toBe(true);
    }
  });

  it('the hint NPCs name Elfheim and Matoya once the fight is won (PT-2: indoors before it)', () => {
    for (const [id, word] of [['old_sailor_hint', 'Elfheim'], ['herbwife_hint', 'Matoya']]) {
      expect(npcOutcome(npc(id), state(['BRIDGE_BUILT']), enc).present, id).toBe(false);
      expect(npcOutcome(npc(id), state(['BRIDGE_BUILT', 'BIKKE_DEFEATED']), enc).dialog.join(' ')).toContain(word);
    }
  });
});

describe('PT-2: Pravoka under the pirates (docs/PLAYTEST_ELFHEIM_PLAN.md)', () => {
  const before = state(['BRIDGE_BUILT']);
  const after = state(['BRIDGE_BUILT', 'BIKKE_DEFEATED']);
  const present = (f: FieldState) => town.npcs.filter((n) => npcOutcome(n, f, town.scriptedEncounters ?? []).present);

  it('before BIKKE_DEFEATED only the pirates and their captain are out; after it the townsfolk are back', () => {
    const out = present(before);
    expect(out.length).toBeGreaterThanOrEqual(7);
    for (const n of out) expect(n.hideIf, `${n.id} is out under the pirates`).toBe('BIKKE_DEFEATED');
    const folk = present(after).filter((n) => !n.hideIf);
    expect(folk.length).toBeGreaterThanOrEqual(10);
    for (const id of ['fishwife', 'fisher', 'lamplighter', 'watchman', 'girl', 'old_man']) {
      expect(folk.map((n) => n.id)).toContain(id);
    }
  });

  it('every shop door is shuttered before the fight and open after it; the inn and the clinic stay open', () => {
    const shops = town.transitions.filter((t) => /^pravoka-(.*-shop|white-magic|black-magic)$/.test(t.targetMap));
    expect(shops).toHaveLength(5);
    for (const t of shops) {
      const g = gateAt(town, { x: t.x, y: t.y });
      expect(g, t.targetMap).not.toBeNull();
      const shut = gateCheck(g!, before);
      expect(shut.open, t.targetMap).toBe(false);
      expect(shut.message).toContain('CLOSED BY ORDER OF CAPTAIN BIKKE');
      expect(gateCheck(g!, after).open, t.targetMap).toBe(true);
    }
    for (const m of ['pravoka-inn', 'pravoka-house-lighthouse']) {
      const t = town.transitions.find((x) => x.targetMap === m)!;
      expect(gateAt(town, { x: t.x, y: t.y }), m).toBeNull();
    }
  });
});

describe('PT-3: every drawn door in Pravoka leads into a room and back out to it', () => {
  type Obj = { type: string; name?: string; door?: number; enter?: { map: string } };
  const objs = (parse(readFileSync('assets-src/maps/pravoka.yaml', 'utf-8')) as { objects: Obj[] }).objects;
  const doors = objs.filter((o) => (o.type === 'house' || o.type === 'prefab') && o.door !== undefined);

  it('every house or prefab with a door has a room behind it (no shut houses left)', () => {
    expect(doors.length).toBeGreaterThanOrEqual(16);
    for (const o of doors) expect(o.enter, `${o.name}'s door leads nowhere`).toBeDefined();
  });

  it('each door: its entrance in front of it, its room, and every way back out to that entrance', () => {
    for (const o of doors) {
      const here = o.name!;
      const [ex, ey] = town.entrances![here] ?? [];
      expect(ex, `${here}: no entrance in front of the door`).toBeDefined();
      const door = town.transitions.find((t) => t.x === ex && t.y === ey - 1)!;
      expect(door, `${here}: no transition on the door`).toBeDefined();
      expect(door.targetMap).toBe(o.enter!.map);
      const room = load(door.targetMap);
      expect(room.entrances![door.targetEntrance!], `${door.targetMap}:${door.targetEntrance}`).toBeDefined();
      const back = room.transitions.filter((t) => t.targetMap === 'pravoka');
      expect(back.length, door.targetMap).toBeGreaterThan(0);
      for (const t of back) expect(t.targetEntrance, door.targetMap).toBe(here);
    }
  });
});

describe('Pravoka: services, flags and the site (B2, 4.0.1)', () => {
  const all = [town, ...rooms.map(load)].flatMap((m) => m.npcs);

  it('the clinic in the lighthouse keeper\'s house charges 10 G a level; the inn costs 50 G', () => {
    const clinic = load('pravoka-house-lighthouse').npcs.filter((n) => n.action === 'clinic');
    expect(clinic.map((n) => n.clinicPrice)).toEqual([10]);
    const shops = parse(readFileSync('assets/data/shops.yaml', 'utf-8')) as Array<{ id: string; type: string; innPrice?: number }>;
    const keepers = all.filter((n) => n.shopId).map((n) => n.shopId!).sort();
    expect(keepers).toEqual(['pravoka_armor', 'pravoka_black', 'pravoka_inn', 'pravoka_item', 'pravoka_weapon', 'pravoka_white']);
    expect(shops.find((s) => s.id === 'pravoka_inn')!.innPrice).toBe(50);
  });

  it('every chest flag is A1-T\'s (CHEST_A1_T_...) and holds a band item, not a key item', () => {
    const chests = all.filter((n) => n.chestItem);
    expect(chests.length).toBeGreaterThanOrEqual(3);
    const items = parse(readFileSync('assets/data/items.yaml', 'utf-8')) as Array<{ id: string; type: string }>;
    for (const c of chests) {
      expect(c.chestFlag).toMatch(/^CHEST_A1_T_/);
      expect(items.find((i) => i.id === c.chestItem)!.type).not.toBe('key');
    }
  });

  it('the site file matches the compiled overworld: the door, the quay dock and the brig on it, off the gate', () => {
    // NW-5: the site file keeps pass W's cells; the NW world placed the site at its new gate, so the door (and the
    // dock) keep their offsets from the gate
    const [gx, gy] = ow.entrances![site.anchor];
    const dx = gx - site.gate[0], dy = gy - site.gate[1];
    const door = ow.transitions.find((t) => t.targetMap === 'pravoka')!;
    expect([door.x, door.y, door.targetEntrance]).toEqual([site.door[0] + dx, site.door[1] + dy, 'gate']);
    const dock = { ...site.dock, x: site.dock.x + dx, y: site.dock.y + dy };
    expect((ow.docks ?? []).find((d) => d.id === site.dock.id)).toEqual(dock);
    const ship = (ow.vehicles ?? []).find((v) => v.type === 'ship')!;
    expect(ship).toMatchObject({ x: dock.x, y: dock.y, requiredFlag: 'BIKKE_DEFEATED' });
    expect(site.spawn).toMatchObject({ x: site.dock.x, y: site.dock.y });
    expect(Math.abs(gx - dock.x) + Math.abs(gy - dock.y)).toBeLessThanOrEqual(2);
  });
});
