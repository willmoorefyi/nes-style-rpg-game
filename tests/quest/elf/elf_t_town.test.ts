const vault = load('elfheim-vault');
const rooms = canonRows().filter((r) => r.owner === 'ELF-T' && r.id !== 'elfheim').map((r) => r.id);
const state = (flags: string[], items: string[] = []): FieldState => ({ flags: new Set(flags), items: new Set(items),
  mode: 'walking', vehicles: [] });
type Step = { type: string; flag?: string; item?: string; map?: string };
const cutscene = (id: string) => (parse(readFileSync('assets/data/cutscenes.yaml', 'utf-8')) as Array<{ id: string; steps: Step[] }>)
  .find((c) => c.id === id);
const site = JSON.parse(execFileSync('python3', ['-I', '-c', 'import json, sys; sys.path.insert(0, "assets-src/tools/layouts/elf"); '
  + 'import town_elfheim_site as S; print(json.dumps({"gate": S.GATE, "door": S.DOOR, "dock": S.DOCK, "anchor": S.ANCHOR}))'],
{ encoding: 'utf-8' })) as { gate: [number, number]; door: [number, number]; dock: { id: string; x: number; y: number }; anchor: string };

/** Walkable cells of a map that cannot reach any of `goals` (4-way, on the terrain alone). */
function cutOff(m: MapData, goals: Array<{ x: number; y: number }>): string[] {
  const ok = (x: number, y: number): boolean => x >= 0 && y >= 0 && x < m.width && y < m.height
    && terrainAllows('walking', baseTerrain(m, x, y));
  const seen = new Set(goals.map((g) => `${g.x},${g.y}`));
  const queue = [...goals];
  while (queue.length) {
    const { x, y } = queue.shift()!;
    for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
      const n = { x: x + dx, y: y + dy };
      if (ok(n.x, n.y) && !seen.has(`${n.x},${n.y}`)) { seen.add(`${n.x},${n.y}`); queue.push(n); }
    }
  }
  const out: string[] = [];
  for (let y = 0; y < m.height; y++) for (let x = 0; x < m.width; x++) if (ok(x, y) && !seen.has(`${x},${y}`)) out.push(`(${x}, ${y})`);
  return out;
}

describe('Elfheim: doors, gates and links (WORLD_PLAN 4.2, canon)', () => {
  it('has the HUD name and its 16 canon maps are built', () => {
    expect(town.name).toBe('Elfheim');
    expect(rooms).toHaveLength(15);
    for (const id of ['elfheim', ...rooms]) {
      expect(readFileSync(`assets-src/maps/${id}.yaml`, 'utf-8').split('\n', 1)[0], id).toMatch(/^# GENERATED by/);
    }
  });

  it('every canon link of the town and the castle: the entrance in front of the door, the room back out to it', () => {
    for (const mid of ['elfheim', 'elfheim-castle']) {
      const m = load(mid);
      const row = canonRows().find((r) => r.id === mid)!;
      for (const [here, map, entrance] of row.links) {
        const doors = m.transitions.filter((t) => t.targetMap === map);
        expect(doors.length, `${mid} -> ${map}`).toBeGreaterThan(0);
        for (const d of doors) expect(d.targetEntrance).toBe(entrance);
        const [ex, ey] = m.entrances![here];
        expect(doors.some((d) => Math.abs(d.x - ex) + Math.abs(d.y - ey) === 1), `${here} beside its door`).toBe(true);
        const back = load(map).transitions.filter((t) => t.targetMap === mid);
        expect(back.length, map).toBeGreaterThan(0);
        for (const t of back) expect(t.targetEntrance).toBe(here);
      }
    }
  });

  it('the south gate leads to overworld:elf_elfheim, and the gate entrance stands inside it', () => {
    const out = town.transitions.filter((t) => t.targetMap === 'overworld');
    expect(out.map((t) => [t.x, t.y, t.targetEntrance])).toEqual([[25, 49, site.anchor], [26, 49, site.anchor]]);
    expect(town.entrances!.gate).toEqual([25, 46]);
  });

  it('EXIT-safe: every walkable cell of the town and of each room reaches its way out (the keepers\' side excepted)', () => {
    expect(cutOff(town, town.transitions.filter((t) => t.targetMap === 'overworld'))).toEqual([]);
    for (const id of rooms) {
      const room = load(id);
      const staff = ((parse(readFileSync(`assets-src/maps/${id}.yaml`, 'utf-8')) as { unreachable_ok?: number[][] })
        .unreachable_ok ?? []).map(([x, y]) => `(${x}, ${y})`);
      const out = id === 'elfheim-castle' ? 'elfheim' : room.transitions[room.transitions.length - 1].targetMap;
      const goals = room.transitions.filter((t) => t.targetMap === out || (id === 'elfheim-castle' && t.targetMap === 'elfheim'));
      expect(cutOff(room, goals).filter((c) => !staff.includes(c)), id).toEqual([]);
    }
  });
});

describe('Elfheim: the prince and the vault (S8, S9)', () => {
  const prince = chamber.npcs.find((n) => n.id === 'elfheim_prince')!;
  const awake = chamber.npcs.find((n) => n.id === 'elfheim_prince_awake')!;

  it('the sleeping prince plays elf_prince_wakes only with the herb (GT-9), and only once', () => {
    expect(prince).toMatchObject({ requiredItem: 'herb', hideIf: 'PRINCE_AWAKE', cutscene: { id: 'elf_prince_wakes', onceFlag: 'PRINCE_AWAKE' } });
    expect(npcOutcome(prince, state([]), []).cutscene).toBeUndefined();
    expect(npcOutcome(prince, state([], ['herb']), []).cutscene).toBe('elf_prince_wakes');
    expect(npcOutcome(prince, state(['PRINCE_AWAKE'], ['herb']), []).present).toBe(false);
    expect(npcOutcome(awake, state([]), []).present).toBe(false);
    expect(npcOutcome(awake, state(['PRINCE_AWAKE']), []).present).toBe(true);
    expect([awake.x, awake.y]).toEqual([prince.x, prince.y]);
  });

  it('elf_prince_wakes takes the herb, gives the Mystic Key, sets PRINCE_AWAKE and reloads the chamber', () => {
    const steps = cutscene('elf_prince_wakes')!.steps;
    expect(steps.filter((s) => s.type === 'take_item').map((s) => s.item)).toEqual(['herb']);
    expect(steps.filter((s) => s.type === 'give_item').map((s) => s.item)).toEqual(['mystic_key']);
    expect(steps.filter((s) => s.type === 'set_flag').map((s) => s.flag)).toEqual(['PRINCE_AWAKE']);
    expect(steps.filter((s) => s.type === 'warp').map((s) => s.map)).toEqual(['elfheim-castle-chamber']);
  });

  it('the vault stair is behind a permanent living gate that opens to the Mystic Key (GT-10)', () => {
    const stair = castle.transitions.filter((t) => t.targetMap === 'elfheim-vault');
    const gates = castle.keyItemGates ?? [];
    expect(gates.map((g) => [g.x, g.y]).sort()).toEqual(stair.map((t) => [t.x, t.y]).sort());
    for (const g of gates) {
      expect(g).toMatchObject({ requiredItem: 'mystic_key', permanent: true, flag: 'ELF_T_VAULT_OPEN' });
      expect(gateCheck(g, state(['PRINCE_AWAKE'])).open).toBe(false);
      expect(gateCheck(g, state([], ['mystic_key'])).open).toBe(true);
    }
  });

  it('the vault holds the TNT (CHEST_ELF_T_TNT) and two band chests', () => {
    const chests = vault.npcs.filter((n) => n.chestItem);
    expect(chests.map((c) => c.chestItem).sort()).toEqual(['ether', 'phoenix_down', 'tnt']);
    expect(chests.find((c) => c.chestItem === 'tnt')!.chestFlag).toBe('CHEST_ELF_T_TNT');
  });
});

describe('Elfheim: the people, services and the site (B3, 4.0.1)', () => {
  const maps = [town, ...rooms.map(load)];
  const all: MapNPC[] = maps.flatMap((m) => m.npcs);
  const says = (n: MapNPC, flags: string[], items: string[] = []): string => npcOutcome(n, state(flags, items), []).dialog.join(' ');

  it('the hints name Matoya and the Marsh Cave before the prince wakes', () => {
    expect(says(town.npcs.find((n) => n.id === 'elfheim_matoya_hint')!, [])).toContain('Matoya');
    expect(says(town.npcs.find((n) => n.id === 'elfheim_marsh_hint')!, [])).toContain('Marsh');
  });

  it('at least 12 townsfolk change their lines on PRINCE_AWAKE', () => {
    const changed = all.filter((n) => !n.chestItem && says(n, []) !== says(n, ['PRINCE_AWAKE']));
    expect(changed.length).toBeGreaterThanOrEqual(12);
  });

  it('the clinic in the healer\'s house charges 20 G a level; the inn costs 100 G; the five shops are kept', () => {
    const clinic = load('elfheim-house-healer').npcs.filter((n) => n.action === 'clinic');
    expect(clinic.map((n) => n.clinicPrice)).toEqual([20]);
    const shops = parse(readFileSync('assets/data/shops.yaml', 'utf-8')) as Array<{ id: string; innPrice?: number }>;
    expect(all.filter((n) => n.shopId).map((n) => n.shopId!).sort()).toEqual(['elfheim_armor', 'elfheim_black',
      'elfheim_inn', 'elfheim_item', 'elfheim_weapon', 'elfheim_white']);
    expect(shops.find((s) => s.id === 'elfheim_inn')!.innPrice).toBe(100);
  });

  it('every chest flag is ELF-T\'s (CHEST_ELF_T_...) and every gate flag ELF_T_', () => {
    for (const c of all.filter((n) => n.chestItem)) expect(c.chestFlag).toMatch(/^CHEST_ELF_T_/);
    for (const g of maps.flatMap((m) => m.keyItemGates ?? [])) expect(g.flag).toMatch(/^ELF_T_/);
  });

  it('the site file matches the compiled overworld: the door at its offset from the gate; the harbour dock', () => {
    // NW-5: the site file keeps pass W's cells; the NW world placed Elfheim at its new gate (the door keeps its offset)
    // and its harbour on the NW shore (ELF's content), so only the dock's id and basin carry over
    const [gx, gy] = ow.entrances![site.anchor];
    const door = ow.transitions.find((t) => t.targetMap === 'elfheim')!;
    expect([door.x, door.y, door.targetEntrance])
      .toEqual([site.door[0] + gx - site.gate[0], site.door[1] + gy - site.gate[1], 'gate']);
    expect((ow.docks ?? []).find((d) => d.id === site.dock.id)).toMatchObject({ id: site.dock.id });
  });
});
