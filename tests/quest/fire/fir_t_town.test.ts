/**
 * FIR-T's town (docs/WORLD_PLAN.md 4.0.1, 4.4, 5.4; S14): Crescent Lake on the compiled maps. The canon entrances and
 * links (every door leads to its room and back to the cell in front of it; the causeway leads to the Circle and
 * back), the land gate's edge exits to `overworld:fir_crescent`, an EXIT-safe plan for the town, the Circle and each
 * room, the elder's canoe (the cutscene `fir_sages_canoe` behind EARTH_CRYSTAL_LIT gives `canoe` and sets
 * CANOE_GIVEN), the twelve sages and their three-step lines, the hints, the clinic and inn prices of band B5, FIR-T's
 * flag prefix, and the site file (`layouts/fire/town_crescent_site.py`, unchanged) agreeing with the compiled
 * overworld.
 */
import { describe, expect, it } from 'vitest';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { parse } from 'yaml';
import type { MapData, MapNPC } from '../../../src/types/index.js';
import { baseTerrain, npcOutcome, terrainAllows, type FieldState } from '../../../src/systems/fieldRules.js';
import { validateMapData } from '../../../src/core/schemaValidation.js';
import { canonRows } from '../questMaps.js';

const load = (id: string): MapData => validateMapData(parse(readFileSync(`assets/maps/ai/${id}.yaml`, 'utf-8'))) as MapData;
const town = load('crescent');
const circle = load('crescent-circle');
const ow = load('overworld');
const rooms = canonRows().filter((r) => r.owner === 'FIR-T' && r.id !== 'crescent' && r.id !== 'crescent-circle').map((r) => r.id);
const state = (flags: string[], items: string[] = []): FieldState => ({ flags: new Set(flags), items: new Set(items), mode: 'walking', vehicles: [] });
type Step = { type: string; flag?: string; item?: string };
const cutscene = (id: string) => (parse(readFileSync('assets/data/cutscenes.yaml', 'utf-8')) as Array<{ id: string; steps: Step[] }>)
  .find((c) => c.id === id);
const site = JSON.parse(execFileSync('python3', ['-I', '-c', 'import json, sys; sys.path.insert(0, "assets-src/tools/layouts/fire"); '
  + 'import town_crescent_site as S; print(json.dumps({"gate": S.GATE, "door": S.DOOR, "dock": S.DOCK, "anchor": S.ANCHOR}))'],
{ encoding: 'utf-8' })) as { gate: [number, number]; door: [number, number]; dock: { id: string; x: number; y: number; basin: string }; anchor: string };

/** Walkable cells of a map that cannot reach any of `goals` (4-way, on the terrain alone). */
function cutOff(m: MapData, goals: Array<{ x: number; y: number }>): string[] {
  const ok = (x: number, y: number): boolean => x >= 0 && y >= 0 && x < m.width && y < m.height
    && terrainAllows('walking', baseTerrain(m, x, y));
  const seen = new Set(goals.map((g) => `${g.x},${g.y}`));
  const queue = [...goals];
  while (queue.length) {
    const { x, y } = queue.shift()!;
    for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
      const n = { x: x + dx, y: y + dy };
      if (ok(n.x, n.y) && !seen.has(`${n.x},${n.y}`)) { seen.add(`${n.x},${n.y}`); queue.push(n); }
    }
  }
  const out: string[] = [];
  for (let y = 0; y < m.height; y++) for (let x = 0; x < m.width; x++) if (ok(x, y) && !seen.has(`${x},${y}`)) out.push(`(${x}, ${y})`);
  return out;
}

describe('Crescent Lake: doors, gate, causeway and links (WORLD_PLAN 4.4, canon)', () => {
  it('has the HUD names and its 14 canon maps are built', () => {
    expect(town.name).toBe('Crescent Lake');
    expect(circle.name).toBe('Circle of Sages');
    expect(rooms).toHaveLength(12);
    for (const id of ['crescent', 'crescent-circle', ...rooms]) {
      expect(readFileSync(`assets-src/maps/${id}.yaml`, 'utf-8').split('\n', 1)[0], id).toMatch(/^# GENERATED by/);
    }
  });

  it('every door link: the entrance in front of the door, the door into the room, the room back out to it', () => {
    const row = canonRows().find((r) => r.id === 'crescent')!;
    for (const [here, map, entrance] of row.links.filter(([, m]) => m !== 'crescent-circle')) {
      const [ex, ey] = town.entrances![here];
      const door = town.transitions.find((t) => t.targetMap === map)!;
      expect(door, `${map}`).toBeDefined();
      expect([door.targetEntrance, door.x, door.y]).toEqual([entrance, ex, ey - 1]);
      const back = load(map).transitions.filter((t) => t.targetMap === 'crescent');
      expect(back.length).toBeGreaterThan(0);
      for (const t of back) expect(t.targetEntrance).toBe(here);
    }
  });

  it('the causeway: the south edge leads to the Circle\'s arrival, and the Circle\'s north edge back to `circle`', () => {
    const out = town.transitions.filter((t) => t.targetMap === 'crescent-circle');
    expect(out.length).toBe(2);
    for (const t of out) expect([t.y, t.targetEntrance]).toEqual([town.height - 1, 'arrival']);
    const [cx, cy] = town.entrances!.circle;
    expect(out.some((t) => t.x === cx && t.y === cy + 1)).toBe(true);
    const back = circle.transitions.filter((t) => t.targetMap === 'crescent');
    expect(back.length).toBe(2);
    for (const t of back) expect([t.y, t.targetEntrance]).toEqual([0, 'circle']);
    expect(circle.entrances!.arrival).toBeDefined();
    expect(circle.exit).toEqual({ map: 'crescent', entrance: 'circle' });
  });

  it('the land gate: the west edge leads to overworld:fir_crescent, and the gate entrance stands inside it', () => {
    const out = town.transitions.filter((t) => t.targetMap === 'overworld');
    expect(out.length).toBeGreaterThan(0);
    for (const t of out) expect([t.x, t.targetEntrance]).toEqual([0, site.anchor]);
    const [gx, gy] = town.entrances!.gate;
    expect(out.some((t) => t.y === gy && t.x === gx - 3)).toBe(true);
  });

  it('EXIT-safe: every walkable cell of the town, the Circle and each room reaches its way out (the keepers\' side excepted)', () => {
    expect(cutOff(town, town.transitions.filter((t) => t.targetMap === 'overworld'))).toEqual([]);
    expect(cutOff(circle, circle.transitions.filter((t) => t.targetMap === 'crescent'))).toEqual([]);
    for (const id of rooms) {
      const room = load(id);
      const staff = ((parse(readFileSync(`assets-src/maps/${id}.yaml`, 'utf-8')) as { unreachable_ok?: number[][] })
        .unreachable_ok ?? []).map(([x, y]) => `(${x}, ${y})`);
      const keeper = room.npcs.find((n) => n.shopId);
      if (keeper) expect(staff, id).toContain(`(${keeper.x}, ${keeper.y})`);
      expect(cutOff(room, room.transitions.filter((t) => t.targetMap === 'crescent')).filter((c) => !staff.includes(c)), id)
        .toEqual([]);
    }
  });
});

describe('Crescent Lake: the Circle of Sages and the canoe (S14)', () => {
  const sage = (id: string): MapNPC => circle.npcs.find((n) => n.id === id)!;
  const beforeLit = ['CANAL_OPEN'];
  const lit = [...beforeLit, 'EARTH_CRYSTAL_LIT'];

  it('twelve sages keep the Circle, Lukahn among them', () => {
    expect(circle.npcs.filter((n) => n.id.startsWith('sage_'))).toHaveLength(12);
    expect(sage('sage_lukahn').dialog.join(' ')).toContain('Lukahn');
  });

  it('the elder plays fir_sages_canoe only once EARTH_CRYSTAL_LIT is set; the cutscene gives the canoe and sets CANOE_GIVEN', () => {
    const elder = sage('sage_elder');
    expect(elder.cutscene).toEqual({ id: 'fir_sages_canoe', requiredFlags: ['EARTH_CRYSTAL_LIT'], onceFlag: 'CANOE_GIVEN' });
    expect(npcOutcome(elder, state(beforeLit), []).cutscene).toBeUndefined();
    expect(npcOutcome(elder, state(beforeLit), []).dialog.join(' ')).toMatch(/Heal the earth first/);
    expect(npcOutcome(elder, state(lit), []).cutscene).toBe('fir_sages_canoe');
    expect(npcOutcome(elder, state([...lit, 'CANOE_GIVEN'], ['canoe']), []).cutscene).toBeUndefined();
    const steps = cutscene('fir_sages_canoe')!.steps;
    expect(steps.filter((s) => s.type === 'give_item').map((s) => s.item)).toEqual(['canoe']);
    expect(steps.filter((s) => s.type === 'set_flag').map((s) => s.flag)).toEqual(['CANOE_GIVEN']);
  });

  it('the canoe is given nowhere else: no chest, gift or other cutscene in FIR-T\'s maps', () => {
    for (const m of [town, circle, ...rooms.map(load)]) {
      for (const n of m.npcs) {
        expect(n.chestItem, n.id).not.toBe('canoe');
        expect(n.giftItem, n.id).not.toBe('canoe');
        if (n.id !== 'sage_elder') expect(n.cutscene, n.id).toBeUndefined();
      }
    }
  });

  it('every other sage speaks of the rotting earth before the crystal, of fire and frost after it, and of the canoe last', () => {
    for (const n of circle.npcs.filter((x) => x.id.startsWith('sage_') && !['sage_elder', 'sage_lukahn'].includes(x.id))) {
      const say = (f: string[]): string => npcOutcome(n, state(f), []).dialog.join(' ');
      const [before, after, canoe] = [say(beforeLit), say(lit), say([...lit, 'CANOE_GIVEN'])];
      expect(new Set([before, after, canoe]).size, n.id).toBe(3);
    }
  });

  it('the hint NPCs name the sages and the volcano at every step of the story', () => {
    for (const [id, word] of [['ferryman_hint', 'sages'], ['geologist_hint', 'volcano']]) {
      const n = town.npcs.find((x) => x.id === id)!;
      for (const f of [beforeLit, lit, [...lit, 'CANOE_GIVEN']]) expect(npcOutcome(n, state(f), []).dialog.join(' '), id).toContain(word);
    }
  });
});

describe('Crescent Lake: services, flags and the site (B5, 4.0.1)', () => {
  const all = [town, circle, ...rooms.map(load)].flatMap((m) => m.npcs);

  it('the clinic in the healer\'s house charges 60 G a level; the inn costs 300 G; the five shops are open', () => {
    const clinic = load('crescent-house-healer').npcs.filter((n) => n.action === 'clinic');
    expect(clinic.map((n) => n.clinicPrice)).toEqual([60]);
    const shops = parse(readFileSync('assets/data/shops.yaml', 'utf-8')) as Array<{ id: string; type: string; innPrice?: number }>;
    const keepers = all.filter((n) => n.shopId).map((n) => n.shopId!).sort();
    expect(keepers).toEqual(['crescent_armor', 'crescent_black', 'crescent_inn', 'crescent_item', 'crescent_weapon', 'crescent_white']);
    expect(shops.find((s) => s.id === 'crescent_inn')!.innPrice).toBe(300);
    for (const k of all.filter((n) => n.shopId)) expect(k.showIf ?? k.hideIf, k.id).toBeUndefined();
  });

  it('every chest flag is FIR-T\'s (CHEST_FIR_T_...) and holds a band item, not a key item', () => {
    const chests = all.filter((n) => n.chestItem);
    expect(chests.length).toBeGreaterThanOrEqual(4);
    const items = parse(readFileSync('assets/data/items.yaml', 'utf-8')) as Array<{ id: string; type: string }>;
    for (const c of chests) {
      expect(c.chestFlag).toMatch(/^CHEST_FIR_T_/);
      expect(items.find((i) => i.id === c.chestItem)!.type).not.toBe('key');
    }
  });

  it('the site file matches the compiled overworld: the door and the dock at their offsets from the gate', () => {
    // NW-5: the site file keeps pass W's cells; the NW world placed the site at its new gate, so the door (and the
    // dock) keep their offsets from the gate
    const [gx, gy] = ow.entrances![site.anchor];
    const dx = gx - site.gate[0], dy = gy - site.gate[1];
    const door = ow.transitions.find((t) => t.targetMap === 'crescent')!;
    expect([door.x, door.y, door.targetEntrance]).toEqual([site.door[0] + dx, site.door[1] + dy, 'gate']);
    expect((ow.docks ?? []).find((d) => d.id === site.dock.id))
      .toEqual({ ...site.dock, x: site.dock.x + dx, y: site.dock.y + dy });
  });
});
